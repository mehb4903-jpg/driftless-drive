#!/usr/bin/env node
/* Patches the Capacitor-generated android/ project (created in CI by `npx cap add android`) for Driftless Drive.
   Idempotent: safe to run again after every `npx cap sync android`.
   - AdMob APPLICATION_ID meta-data, read from DD_ADS_CONFIG.appId in index.html (the one place for ad ids)
   - landscape only, fullscreen / immersive (status and navigation bars hidden), screen kept on
   - WebView: audio and video play without a tap, third-party cookies for the YouTube embed
   - launcher icon from icons/icon-512.png
   - versionCode / versionName from DD_VERSION_CODE / DD_VERSION_NAME (set by the workflow) */
'use strict';
const fs = require('fs'), path = require('path');
const root = path.resolve(__dirname, '..'), app = path.join(root, 'android', 'app');
const rel = p => path.join(app, p);
if (!fs.existsSync(app)) { console.error('android/app not found. Run `npx cap add android` first.'); process.exit(1); }

/* 1. AdMob app id from index.html */
const html = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
const cfgAt = html.indexOf('window.DD_ADS_CONFIG');
const m = cfgAt >= 0 && /appId:\s*'(ca-app-pub-\d+~\d+)'/.exec(html.slice(cfgAt, cfgAt + 2000));
if (!m) { console.error('Could not find DD_ADS_CONFIG.appId (ca-app-pub-...~...) in index.html'); process.exit(1); }
const ADMOB_APP_ID = m[1];

/* 2. AndroidManifest.xml */
const manPath = rel('src/main/AndroidManifest.xml');
let man = fs.readFileSync(manPath, 'utf8');
man = man.replace(/\s*<meta-data android:name="com\.google\.android\.gms\.ads\.APPLICATION_ID"[^>]*\/>/g, '');
man = man.replace(/(<application\b[^>]*>)/, `$1\n        <meta-data android:name="com.google.android.gms.ads.APPLICATION_ID" android:value="${ADMOB_APP_ID}"/>`);
if (!/android:screenOrientation=/.test(man)) man = man.replace(/(android:name="\.MainActivity")/, '$1\n            android:screenOrientation="sensorLandscape"');
if (!/android:hardwareAccelerated=/.test(man)) man = man.replace(/(<application\b)/, '$1\n        android:hardwareAccelerated="true"');
fs.writeFileSync(manPath, man);

/* 3. MainActivity: immersive fullscreen, keep screen on, WebView media + cookies */
const actDir = rel('src/main/java/com/driftless/drive');
fs.mkdirSync(actDir, { recursive: true });
fs.writeFileSync(path.join(actDir, 'MainActivity.java'), `package com.driftless.drive;

import android.os.Build;
import android.os.Bundle;
import android.view.WindowManager;
import android.webkit.CookieManager;
import android.webkit.WebSettings;
import android.webkit.WebView;
import androidx.core.view.WindowCompat;
import androidx.core.view.WindowInsetsCompat;
import androidx.core.view.WindowInsetsControllerCompat;
import com.getcapacitor.BridgeActivity;

/* Generated by scripts/patch-android.js. Edit that script, not this file. */
public class MainActivity extends BridgeActivity {
    @Override
    public void onCreate(Bundle savedInstanceState) {
        super.onCreate(savedInstanceState);
        getWindow().addFlags(WindowManager.LayoutParams.FLAG_KEEP_SCREEN_ON);
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.P) {
            getWindow().getAttributes().layoutInDisplayCutoutMode = WindowManager.LayoutParams.LAYOUT_IN_DISPLAY_CUTOUT_MODE_SHORT_EDGES;
        }
        hideSystemBars();
        WebView wv = getBridge() != null ? getBridge().getWebView() : null;
        if (wv != null) {
            WebSettings s = wv.getSettings();
            s.setMediaPlaybackRequiresUserGesture(false);
            s.setJavaScriptEnabled(true);
            s.setDomStorageEnabled(true);
            CookieManager.getInstance().setAcceptCookie(true);
            CookieManager.getInstance().setAcceptThirdPartyCookies(wv, true);
        }
    }

    @Override
    public void onResume() {
        super.onResume();
        hideSystemBars();
    }

    @Override
    public void onWindowFocusChanged(boolean hasFocus) {
        super.onWindowFocusChanged(hasFocus);
        if (hasFocus) hideSystemBars();
    }

    private void hideSystemBars() {
        WindowCompat.setDecorFitsSystemWindows(getWindow(), false);
        WindowInsetsControllerCompat c = WindowCompat.getInsetsController(getWindow(), getWindow().getDecorView());
        if (c == null) return;
        c.hide(WindowInsetsCompat.Type.systemBars());
        c.setSystemBarsBehavior(WindowInsetsControllerCompat.BEHAVIOR_SHOW_TRANSIENT_BARS_BY_SWIPE);
    }
}
`);

/* 4. launcher icon: the game's 512 px icon (Android scales it down for each density) */
const icon = path.join(root, 'icons', 'icon-512.png');
const res = rel('src/main/res');
for (const f of ['ic_launcher.xml', 'ic_launcher_round.xml']) fs.rmSync(path.join(res, 'mipmap-anydpi-v26', f), { force: true });
for (const d of fs.readdirSync(res).filter(d => d.startsWith('mipmap-') && d !== 'mipmap-anydpi-v26')) {
  for (const f of ['ic_launcher.png', 'ic_launcher_round.png', 'ic_launcher_foreground.png']) fs.rmSync(path.join(res, d, f), { force: true });
}
fs.mkdirSync(path.join(res, 'mipmap-xxxhdpi'), { recursive: true });
for (const f of ['ic_launcher.png', 'ic_launcher_round.png']) fs.copyFileSync(icon, path.join(res, 'mipmap-xxxhdpi', f));

/* 5. version from the workflow (tag name and run number) */
const gPath = rel('build.gradle');
let g = fs.readFileSync(gPath, 'utf8');
const vc = parseInt(process.env.DD_VERSION_CODE || '', 10), vn = (process.env.DD_VERSION_NAME || '').replace(/[^\w.+-]/g, '');
if (Number.isFinite(vc) && vc > 0) g = g.replace(/versionCode \d+/, 'versionCode ' + vc);
if (vn) g = g.replace(/versionName "[^"]*"/, 'versionName "' + vn + '"');
if (!/checkReleaseBuilds/.test(g)) g = g.replace(/android \{/, 'android {\n    lint { checkReleaseBuilds false; abortOnError false }   // added by scripts/patch-android.js: no lint pass in the release build');
fs.writeFileSync(gPath, g);

console.log('android/ patched. AdMob app id:', ADMOB_APP_ID, vn ? '| version ' + vn + ' (' + vc + ')' : '');
